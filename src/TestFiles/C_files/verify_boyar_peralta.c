/* ── Boyer-Peralta S-box under test ─────────────────────────────────── */
/* Forward declaration so the #include below sees it as a definition */
void sbox(
    bool i0, bool i1, bool i2, bool i3,
    bool i4, bool i5, bool i6, bool i7, bool dec_1,
    bool *y0, bool *y1, bool *y2, bool *y3,
    bool *y4, bool *y5, bool *y6, bool *y7);

#include "Boyer_Peraltas_sbox.c"

/* ── Exhaustive test over all 256 input bytes ────────────────────────── */
int main(void) {
    int errors = 0;

    for (int in = 0; in < 256; in++) {
        /* Unpack input byte into individual bits; i0 = LSB, i7 = MSB */
        bool i0 = (in >> 0) & 1, i1 = (in >> 1) & 1,
             i2 = (in >> 2) & 1, i3 = (in >> 3) & 1,
             i4 = (in >> 4) & 1, i5 = (in >> 5) & 1,
             i6 = (in >> 6) & 1, i7 = (in >> 7) & 1;

        bool y0, y1, y2, y3, y4, y5, y6, y7;

        /* dec_1 must be true — it is used as a constant 1 for XNOR outputs */
        sbox(i0, i1, i2, i3, i4, i5, i6, i7, /*dec_1=*/true,
             &y0, &y1, &y2, &y3, &y4, &y5, &y6, &y7);

        /* Repack output bits; y0 = LSB, y7 = MSB */
        uint8_t out = (uint8_t)(
            ((int)y0)       | (((int)y1) << 1) | (((int)y2) << 2) |
            (((int)y3) << 3) | (((int)y4) << 4) | (((int)y5) << 5) |
            (((int)y6) << 6) | (((int)y7) << 7));

        uint8_t ref = AES_SBOX[in];
        if (out != ref) {
            printf("[FAIL] in=0x%02X  got=0x%02X  expected=0x%02X\n",
                   in, out, ref);
            errors++;
        }
    }

    if (errors == 0)
        printf("[PASS] All 256 S-box outputs are correct.\n");
    else
        printf("[FAIL] %d / 256 mismatches.\n", errors);

    return errors ? 1 : 0;
}
