//======================================================================
// Main function to VERIFY the shared sbox against the CSV file
//======================================================================
int main() {
    FILE *fp;
    const char *filename = "sbox_test_vectors.csv";
    
    // Open the CSV file for reading
    fp = fopen(filename, "r");
    if (fp == NULL) {
        perror("Error: Cannot open sbox_test_vectors.csv for reading. Please generate it first");
        return 1;
    }

    // Seed the random number generator
    srand(time(NULL));

    // Buffer to read and discard the header line ("Input,Output")
    char header_buffer[128];
    if (fgets(header_buffer, sizeof(header_buffer), fp) == NULL) {
        fprintf(stderr, "Error: Could not read header from CSV file.\n");
        fclose(fp);
        return 1;
    }

    int input_from_file, expected_output;
    int tests_run = 0;
    int failures = 0;

    printf("Verifying shared sbox implementation against '%s'...\n", filename);

    // Loop through the CSV file, reading one line at a time
    while (fscanf(fp, "%d,%d\n", &input_from_file, &expected_output) == 2) {
        tests_run++;

        // 1. Split the input into two random shares
        int n_0 = rand() % 256;
        int n_1 = n_0 ^ input_from_file;
        
        // 2. Declare variables for the output shares
        int actual_output_0, actual_output_1;

        // 3. Call the shared sbox function with shares and random numbers
        sbox(
            n_0, n_1,
            &actual_output_0, &actual_output_1,
            // Decimal constants
            0, 1, 255, 169, 129, 9, 72, 242, 243, 152, 240, 4, 15, 12, 2, 3, 36, 220, 11, 158, 45, 88, 99,
            // Random numbers for gadgets
            rand()%256, rand()%256, rand()%256, rand()%256, rand()%256, rand()%256, rand()%256, rand()%256, rand()%256, rand()%256,
            rand()%256, rand()%256, rand()%256, rand()%256, rand()%256, rand()%256, rand()%256, rand()%256, rand()%256, rand()%256,
            rand()%256, rand()%256, rand()%256, rand()%256, rand()%256, rand()%256, rand()%256, rand()%256, rand()%256, rand()%256,
            rand()%256, rand()%256, rand()%256, rand()%256, rand()%256, rand()%256
        );

        // 4. Combine the output shares to get the final result
        int combined_output = actual_output_0 ^ actual_output_1;

        // 5. Compare the result with the expected output from the file
        if (combined_output != expected_output) {
            failures++;
            printf("\n--- MISMATCH FOUND! ---\n");
            printf("  Input:           %d\n", input_from_file);
            printf("  Shares (n_0, n_1): (%d, %d)\n", n_0, n_1);
            printf("  Expected Output: %d\n", expected_output);
            printf("  Actual Shares:   (%d, %d)\n", actual_output_0, actual_output_1);
            printf("  Combined Output: %d\n", combined_output);
        }
    }

    fclose(fp);

    // Print the final summary of the verification
    printf("\n--------------------------\n");
    printf("Verification Complete.\n");
    printf("Total Tests Run: %d\n", tests_run);

    if (failures == 0) {
        printf("✅ Success! All %d test vectors passed.\n", tests_run);
    } else {
        printf("❌ Failure! Found %d mismatch(es) out of %d tests.\n", failures, tests_run);
    }

    // Return 0 on success, 1 on failure
    return (failures == 0) ? 0 : 1;
}

